// Production build: minifies the inline CSS and JS of index.html, pins them with CSP hashes
// (no 'unsafe-inline'), enforces Trusted Types, and copies assets to dist/.
import { createHash } from "node:crypto";
import { transform } from "esbuild";
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const html = readFileSync("index.html", "utf8");
let out = html;
const hashes = { style: [], script: [] };
const sha = (code) => `'sha256-${createHash("sha256").update(code, "utf8").digest("base64")}'`;
for (const m of html.matchAll(/<style>([\s\S]*?)<\/style>/g)) {
  const code = (await transform(m[1], { loader: "css", minify: true, target: ["chrome110", "firefox115", "safari16"] })).code.trim();
  hashes.style.push(sha(code));
  out = out.replace(m[0], `<style>${code}</style>`);
}
for (const m of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) {
  const code = (await transform(m[1], { loader: "js", minify: true, target: "es2022" })).code.trim();
  hashes.script.push(sha(code));
  out = out.replace(m[0], `<script>${code}</script>`);
}
out = out.replace(/\n\s*\n/g, "\n");

const csp = [
  "default-src 'none'",
  "img-src 'self' data:",
  "connect-src 'self'",
  `style-src ${hashes.style.join(" ")}`,
  `script-src ${hashes.script.join(" ")}`,
  "base-uri 'none'",
  "form-action 'none'",
  "object-src 'none'",
  "require-trusted-types-for 'script'",
  "trusted-types 'none'",
];
// Hosts that read _headers get the full policy; the meta tag covers everything except frame-ancestors.
const headers = `# Generated by apps/site/build.mjs — do not edit by hand.
/*
  Content-Security-Policy: ${[...csp, "frame-ancestors 'none'"].join("; ")}
  X-Frame-Options: DENY
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Strict-Transport-Security: max-age=31536000; includeSubDomains
  Permissions-Policy: camera=(), microphone=(), geolocation=(), interest-cohort=()
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
/
  Cache-Control: no-cache
/assets/*
  Cache-Control: public, max-age=31536000, immutable
`;
out = out.replace('<meta name="color-scheme" content="dark">', `<meta name="color-scheme" content="dark">\n<meta http-equiv="Content-Security-Policy" content="${csp.join("; ")}">`);

rmSync("dist", { recursive: true, force: true });
mkdirSync("dist", { recursive: true });
writeFileSync("dist/index.html", out);
writeFileSync("dist/_headers", headers);
cpSync("assets", "dist/assets", { recursive: true });
cpSync("robots.txt", "dist/robots.txt");
console.log(`site: ${html.length} → ${out.length} bytes (index.html), CSP pinned to ${hashes.style.length} style + ${hashes.script.length} script hash(es)`);
